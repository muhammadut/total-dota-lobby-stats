/* ═══════════════════════════════════════════════════════════════════
   The Ancients' Ledger — view layer.
   Reads window.LOBBY (see data.js, generated by export_web.py).
   No framework, no build step: the whole point is that this stays a
   folder of three files GitHub Pages can serve forever.
   ═══════════════════════════════════════════════════════════════════ */
(function () {
  "use strict";

  var D = window.LOBBY;
  if (!D) { console.error("data.js did not load"); return; }

  var $  = function (s, r) { return (r || document).querySelector(s); };
  var el = function (t, c, h) {
    var n = document.createElement(t);
    if (c) n.className = c;
    if (h !== undefined) n.innerHTML = h;
    return n;
  };
  // Every string from the data file passes through here before it can
  // reach innerHTML. Player names are user-chosen and contain <, >, ¤, ™.
  var esc = function (s) {
    return String(s === null || s === undefined ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  };
  var num  = function (n) { return n === null || n === undefined ? "—" : Number(n).toLocaleString("en-US"); };
  var dur  = function (s) { return s ? Math.floor(s / 60) + ":" + String(s % 60).padStart(2, "0") : "—"; };
  var pct  = function (n) { return n === null || n === undefined ? "—" : n.toFixed(1) + "%"; };
  var ratio = function (n) { return n === null || n === undefined ? "∞" : n.toFixed(2); };

  var MONTHS = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"];
  function prettyDate(iso) {
    if (!iso) return "—";
    var p = iso.split(" ");
    var d = p[0].split("-");
    var out = Number(d[2]) + " " + MONTHS[Number(d[1]) - 1] + " " + d[0];
    return p[1] ? out + " · " + p[1] : out;
  }

  /* ── Masthead ─────────────────────────────────────────────────── */
  function masthead() {
    var m = D.meta;
    $("#sessionDates").textContent =
      m.sessionFrom === m.sessionTo
        ? "A single evening — " + prettyDate(m.sessionFrom)
        : prettyDate(m.sessionFrom) + " – " + prettyDate(m.sessionTo);

    // "Player-games", not "games": 7 matches x 10 players = 70 scoreboard
    // lines. Sitting next to "Matches 7", anything vaguer reads as though
    // seventy games were played.
    var tally = [
      ["Matches",  m.matches,      "Matches played in this lobby"],
      ["Players",  m.players,      "Distinct people, after merging renamed accounts"],
      ["Player-games", m.appearances,
        m.matches + " matches × 10 players — one scoreboard line each"],
      ["Heroes drafted", D.heroes.length, "Distinct heroes picked at least once"],
      ["Kills", num(m.totalKills), "Hero kills across every match"]
    ];
    var wrap = $("#tally");
    tally.forEach(function (t) {
      var d = el("div");
      d.title = t[2];
      d.appendChild(el("dt", null, esc(t[0])));
      d.appendChild(el("dd", null, esc(t[1])));
      wrap.appendChild(d);
    });

    var al = D.meta.aliases || [];
    $("#aliasNote").innerHTML = al.length
      ? esc(al.length) + " name" + (al.length === 1 ? " was" : "s were") + " merged this way."
      : "";
    $("#generated").textContent = "Ledger of " + prettyDate(m.sessionTo);
  }

  /* ── Standings ────────────────────────────────────────────────── */
  var sortKey = "games", sortDir = -1;

  function drawStandings() {
    var tb = $("#standings tbody");
    tb.innerHTML = "";

    var list = D.players.slice().sort(function (a, b) {
      var x = a[sortKey], y = b[sortKey];
      if (sortKey === "name") return sortDir * String(x).localeCompare(String(y));
      // Undefined ratios (never lost / never died) sort as best, not worst.
      // Undefined ratios sort as best, not worst, whichever way we're going.
      if (x === null || x === undefined) x = sortDir === -1 ? Infinity : -Infinity;
      if (y === null || y === undefined) y = sortDir === -1 ? Infinity : -Infinity;
      if (x !== y) return sortDir * (x - y);
      // Ties break on evidence first, then performance, then name -- so
      // sorting by games can never put a 1-4 record above a 3-2 one.
      if (a.games !== b.games)     return b.games - a.games;
      if (a.win_pct !== b.win_pct) return b.win_pct - a.win_pct;
      return String(a.name).localeCompare(String(b.name));
    });

    list.forEach(function (p, i) {
      var tr = el("tr");
      tr.style.setProperty("--i", i);
      if (i < 3 && sortKey === "games") tr.classList.add("is-top");
      tr.tabIndex = 0;
      tr.setAttribute("role", "button");
      tr.setAttribute("aria-label", "Open record for " + p.name);

      var w = p.win_pct === null ? 0 : p.win_pct;
      tr.innerHTML =
        '<td><span class="rank">' + (i + 1) + "</span></td>" +
        '<td class="col-name"><span class="p-name">' + esc(p.name) + "</span></td>" +
        "<td>" + p.games + "</td>" +
        '<td class="w-num">' + p.wins + "</td>" +
        '<td class="l-num">' + p.losses + "</td>" +
        '<td><div class="bar' + (w === 0 ? " bar--blank" : "") + '">' +
          (w > 0 ? '<div class="bar__fill" style="width:' + w + '%"></div>' : "") +
        "</div></td>" +
        '<td class="pct">' + pct(p.win_pct) + "</td>" +
        '<td class="col-kda">' + p.kills + " / " + p.deaths + " / " + p.assists + "</td>" +
        "<td>" + ratio(p.kda) + "</td>" +
        '<td class="col-opt dim">' + num(p.avg_gpm) + "</td>";

      tr.addEventListener("click", function () { openDrawer(p); });
      tr.addEventListener("keydown", function (e) {
        if (e.key === "Enter" || e.key === " ") { e.preventDefault(); openDrawer(p); }
      });
      tb.appendChild(tr);
    });
  }

  function wireSorting() {
    Array.prototype.forEach.call(document.querySelectorAll("#standings th[data-sort]"), function (th) {
      th.addEventListener("click", function () {
        var k = th.getAttribute("data-sort");
        if (k === sortKey) { sortDir = -sortDir; }
        else { sortKey = k; sortDir = (k === "name") ? 1 : -1; }
        Array.prototype.forEach.call(document.querySelectorAll("#standings th"), function (o) {
          o.removeAttribute("aria-sort");
        });
        th.setAttribute("aria-sort", sortDir === 1 ? "ascending" : "descending");
        drawStandings();
      });
    });
  }

  /* ── Matches ──────────────────────────────────────────────────── */
  var BOARD_COLS = [
    ["hero",       "Hero"],
    ["hero_level", "Lvl"],
    ["kda",        "K / D / A"],
    ["net_worth",  "Net"],
    ["last_hits",  "LH / DN"],
    ["gpm",        "GPM"],
    ["xpm",        "XPM"],
    ["hero_damage","Hero dmg"]
  ];

  function boardTable(side, roster, label, won) {
    var t = el("table", "board");
    var cap = el("caption", side, esc(label) + (won ? " — victory" : ""));
    t.appendChild(cap);

    var head = el("tr");
    head.appendChild(el("th", null, "Player"));
    BOARD_COLS.forEach(function (c) { head.appendChild(el("th", null, c[1])); });
    var thead = el("thead"); thead.appendChild(head); t.appendChild(thead);

    var tb = el("tbody");
    roster.forEach(function (r) {
      var tr = el("tr");
      tr.innerHTML =
        '<td class="b-player">' + esc(r.player_name) + "</td>" +
        '<td class="b-hero">' + esc(r.hero || "—") + "</td>" +
        "<td>" + (r.hero_level || "—") + "</td>" +
        "<td>" + r.kills + " / " + r.deaths + " / " + r.assists + "</td>" +
        "<td>" + num(r.net_worth) + "</td>" +
        "<td>" + num(r.last_hits) + " / " + num(r.denies) + "</td>" +
        "<td>" + num(r.gpm) + "</td>" +
        "<td>" + num(r.xpm) + "</td>" +
        "<td>" + num(r.hero_damage) + "</td>";
      tb.appendChild(tr);
    });
    t.appendChild(tb);
    return t;
  }

  function drawMatches() {
    var wrap = $("#matches");
    // Newest first for reading; the data arrives in true chronological order.
    D.matches.slice().reverse().forEach(function (m, i) {
      var rWon = m.winning_side === "radiant";
      var card = el("div", "match");
      card.style.setProperty("--i", i);

      var head = el("button", "match__head");
      head.setAttribute("aria-expanded", "false");
      head.innerHTML =
        '<span class="match__seq">' + String(m.seq).padStart(2, "0") + "</span>" +
        '<span class="side side--radiant' + (rWon ? "" : " is-loser") + '">' +
          '<span class="side__name">' + esc(m.radiant_team_name || "The Radiant") + "</span>" +
          '<span class="side__tag">Radiant</span>' +
        "</span>" +
        '<span class="match__score">' +
          '<span class="' + (rWon ? "win" : "") + '">' + m.radiant_score + "</span>" +
          '<span class="sep">—</span>' +
          '<span class="' + (rWon ? "" : "win") + '">' + m.dire_score + "</span>" +
        "</span>" +
        '<span class="side side--dire side--r' + (rWon ? " is-loser" : "") + '">' +
          '<span class="side__name">' + esc(m.dire_team_name || "The Dire") + "</span>" +
          '<span class="side__tag">Dire</span>' +
        "</span>" +
        '<span class="match__meta">' +
          "<span>" + esc(dur(m.duration_seconds)) + "</span>" +
          "<span>" + esc(m.played_at ? m.played_at.split(" ")[1] : "time n/a") + "</span>" +
          '<span class="match__chevron" aria-hidden="true"></span>' +
        "</span>";

      var body  = el("div", "match__body");
      var inner = el("div", "match__inner");
      var s1 = el("div", "board-scroll"); s1.appendChild(boardTable("radiant", m.radiant, m.radiant_team_name || "The Radiant", rWon));
      var s2 = el("div", "board-scroll"); s2.appendChild(boardTable("dire",    m.dire,    m.dire_team_name    || "The Dire",   !rWon));
      inner.appendChild(s1);
      inner.appendChild(s2);
      if (m.notes) inner.appendChild(el("p", "match__note", esc(m.notes)));
      body.appendChild(inner);

      head.addEventListener("click", function () {
        var open = card.classList.toggle("is-open");
        head.setAttribute("aria-expanded", open ? "true" : "false");
      });

      card.appendChild(head);
      card.appendChild(body);
      wrap.appendChild(card);
    });
  }

  /* ── Heroes ───────────────────────────────────────────────────── */
  function drawHeroes() {
    var wrap = $("#heroes");
    D.heroes.forEach(function (h, i) {
      var w = Math.round((h.wins / h.picks) * 100);
      var c = el("div", "hero");
      c.style.setProperty("--i", i);
      c.innerHTML =
        '<div class="hero__name">' + esc(h.hero) + "</div>" +
        '<div class="hero__line"><span>' + h.picks + (h.picks === 1 ? " pick" : " picks") +
          "</span><span>" + h.wins + "W · " + h.losses + "L</span></div>" +
        '<div class="hero__bar"><span style="width:' + w + '%"></span></div>' +
        '<div class="hero__who">' + esc(h.players.join(", ")) + "</div>";
      wrap.appendChild(c);
    });
  }

  /* ── Player drawer ────────────────────────────────────────────── */
  var drawer = $("#drawer"), scrim = $("#scrim"), lastFocus = null;

  function openDrawer(p) {
    lastFocus = document.activeElement;
    var body = $("#drawerBody");
    var stats = [
      ["Games", p.games], ["Won", p.wins], ["Lost", p.losses],
      ["Win rate", pct(p.win_pct)], ["KDA", ratio(p.kda)]
    ];
    var html =
      '<p class="d-eyebrow">Player record</p>' +
      '<h2 class="d-name" id="drawerName">' + esc(p.name) + "</h2>" +
      '<dl class="d-stats">' + stats.map(function (s) {
        return "<div><dt>" + esc(s[0]) + "</dt><dd>" + esc(s[1]) + "</dd></div>";
      }).join("") + "</dl>";

    html += '<p class="d-sub">Averages</p><dl class="d-stats">' +
      [["GPM", num(p.avg_gpm)], ["XPM", num(p.avg_xpm)],
       ["Net worth", num(p.avg_net)], ["Best net", num(p.best_net)]]
      .map(function (s) { return "<div><dt>" + esc(s[0]) + "</dt><dd>" + esc(s[1]) + "</dd></div>"; })
      .join("") + "</dl>";

    html += '<p class="d-sub">Match by match</p>';
    p.history.forEach(function (h) {
      html +=
        '<div class="d-row">' +
          '<span class="d-flag ' + (h.won ? "w" : "l") + '">' + (h.won ? "Win" : "Loss") + "</span>" +
          "<span><span class='d-hero'>" + esc(h.hero || "—") + "</span><br>" +
            '<span class="d-when">' + esc(prettyDate(h.played)) + "</span></span>" +
          '<span class="d-kda">' + h.k + "/" + h.d + "/" + h.a +
            "<br><span class='d-when'>" + num(h.net) + " net</span></span>" +
        "</div>";
    });

    if (p.heroes.length) {
      html += '<p class="d-sub">Heroes played</p>';
      p.heroes.forEach(function (h) {
        html +=
          '<div class="d-row">' +
            '<span class="d-flag ' + (h.wins === h.picks ? "w" : (h.wins ? "w" : "l")) + '">' +
              h.wins + "/" + h.picks + "</span>" +
            '<span class="d-hero">' + esc(h.hero) + "</span>" +
            '<span class="d-kda">' + (h.picks === 1 ? "once" : h.picks + " picks") + "</span>" +
          "</div>";
      });
    }

    body.innerHTML = html;
    drawer.hidden = false; scrim.hidden = false;
    document.body.style.overflow = "hidden";
    $("#drawerClose").focus();
  }

  function closeDrawer() {
    drawer.hidden = true; scrim.hidden = true;
    document.body.style.overflow = "";
    if (lastFocus) lastFocus.focus();
  }

  /* ── Tabs ─────────────────────────────────────────────────────── */
  function wireTabs() {
    Array.prototype.forEach.call(document.querySelectorAll(".tab"), function (t) {
      t.addEventListener("click", function () {
        Array.prototype.forEach.call(document.querySelectorAll(".tab"), function (o) {
          o.classList.remove("is-active"); o.setAttribute("aria-selected", "false");
        });
        Array.prototype.forEach.call(document.querySelectorAll(".view"), function (v) {
          v.classList.remove("is-active");
        });
        t.classList.add("is-active"); t.setAttribute("aria-selected", "true");
        $("#view-" + t.getAttribute("data-view")).classList.add("is-active");
      });
    });
  }

  masthead();
  drawStandings();
  wireSorting();
  drawMatches();
  drawHeroes();
  wireTabs();

  $("#drawerClose").addEventListener("click", closeDrawer);
  scrim.addEventListener("click", closeDrawer);
  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape" && !drawer.hidden) closeDrawer();
  });
})();
